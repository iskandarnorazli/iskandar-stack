#!/usr/bin/env python3
"""Shared task state for Claude and Antigravity.

One folder per task under <repo>/.agents/state/<id>/:
  STATE.md       goal, plan, tasks, handoff, walkthrough, and a Mermaid chart of the lifecycle
  DECISIONS.tsv  append-only decision log (pstack show-me-your-work format)

Every write goes through parse -> model -> render, so hand edits are tolerated and
the file stays canonical. Standard library only; runs on Windows and Linux.
"""
from __future__ import annotations

import argparse
import datetime as _dt
import os
import re
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

PHASES = ("plan", "build", "verify", "review", "done", "paused", "blocked")
ACTIVE = ("plan", "build", "verify", "review")
TRANSITIONS = {
    "plan": ("build", "review"),
    "build": ("verify",),
    "verify": ("build", "review"),
    "review": ("build", "done"),
    "done": ("build",),
}
OWNERS = ("claude", "antigravity", "human")
SECTIONS = ("Goal", "Plan", "Tasks", "Handoff", "Walkthrough")
# What a handoff asks the receiver to do, and the phases where that makes sense.
HANDOFF_PHASES = {
    "plan": ("plan",),
    "build": ("plan", "build", "verify"),
    "review": ("review",),
    "decide": ACTIVE + ("paused", "blocked"),
}
LOG_HEADER = ("ts", "phase", "decision", "why", "evidence", "result")
ID_RE = re.compile(r"^[a-z0-9][a-z0-9._-]{0,63}$")
TASK_RE = re.compile(r"^- \[( |x|X|-)\] (.*)$")
SKIP_RE = re.compile(r"^(.*?)\s+(?:—|--)\s+skip:\s*(.+)$")
CHART_START = "<!-- chart:start (generated by state.py, do not edit) -->"
CHART_END = "<!-- chart:end -->"


class StateError(Exception):
    pass


def now() -> str:
    return _dt.datetime.now(_dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


@dataclass
class Task:
    text: str
    status: str = "open"  # open | done | skip
    reason: str = ""

    def render(self) -> str:
        if self.status == "done":
            return f"- [x] {self.text}"
        if self.status == "skip":
            return f"- [-] {self.text} -- skip: {self.reason}"
        return f"- [ ] {self.text}"


@dataclass
class State:
    meta: dict = field(default_factory=dict)
    sections: dict = field(default_factory=dict)
    tasks: list = field(default_factory=list)

    @property
    def id(self) -> str:
        return self.meta.get("id", "")

    @property
    def phase(self) -> str:
        return self.meta.get("phase", "")


# ---------------------------------------------------------------- locations

def find_root(start: Path) -> Path:
    for p in [start, *start.parents]:
        if (p / ".git").exists():
            return p
    return start


def state_dir(args) -> Path:
    env = os.environ.get("ISKANDAR_STATE_DIR")
    if env:
        return Path(env)
    root = Path(args.root) if args.root else find_root(Path.cwd())
    return root / ".agents" / "state"


def task_dir(args, tid: str) -> Path:
    if not ID_RE.match(tid):
        raise StateError(f"bad task id {tid!r}: use lowercase letters, digits, '.', '_' or '-'")
    return state_dir(args) / tid


# ---------------------------------------------------------------- parse / render

def parse(text: str) -> State:
    text = text.replace("\r\n", "\n")
    st = State()
    lines = text.split("\n")
    i = 0
    if lines and lines[0].strip() == "---":
        i = 1
        while i < len(lines) and lines[i].strip() != "---":
            m = re.match(r"^([A-Za-z_]+):\s*(.*?)\s*$", lines[i])
            if m:
                st.meta[m.group(1)] = m.group(2)
            i += 1
        i += 1
    current = None
    buf: dict = {}
    in_chart = False
    for line in lines[i:]:
        if line.strip() == CHART_START:
            in_chart = True
            continue
        if line.strip() == CHART_END:
            in_chart = False
            continue
        if in_chart:
            continue
        m = re.match(r"^## (.+?)\s*$", line)
        # Only the known sections split the file; any other "##" heading (a plan's
        # "## Proposed Changes", say) belongs to the section it sits in.
        if m and (m.group(1) in SECTIONS or m.group(1) == "State" or current is None):
            current = m.group(1)
            buf.setdefault(current, [])
            continue
        if current is not None:
            buf[current].append(line)
    for name, body in buf.items():
        if name == "Tasks":
            for line in body:
                tm = TASK_RE.match(line.strip())
                if not tm:
                    continue
                mark, rest = tm.group(1), tm.group(2).strip()
                if mark == "-":
                    sm = SKIP_RE.match(rest)
                    st.tasks.append(Task(sm.group(1).strip(), "skip", sm.group(2).strip()) if sm else Task(rest, "skip", ""))
                else:
                    st.tasks.append(Task(rest, "done" if mark in "xX" else "open"))
        elif name != "State":
            st.sections[name] = "\n".join(body).strip("\n")
    return st


def chart(st: State, visited: set) -> str:
    out = ["stateDiagram-v2"]
    out.append("    direction LR")
    out.append("    [*] --> plan")
    for src, dsts in TRANSITIONS.items():
        for d in dsts:
            out.append(f"    {src} --> {d}")
    out.append("    done --> [*]")
    cur = st.phase
    prev = st.meta.get("previous", "")
    if cur in ("paused", "blocked"):
        out.append(f"    {prev or 'plan'} --> {cur}: {st.meta.get('pause_reason', cur)}")
    owner = st.meta.get("owner", "")
    out.append(f"    note right of {cur if cur in PHASES else 'plan'}: owner {owner}")
    out.append("    classDef current fill:#f4b400,color:#000,stroke:#000,stroke-width:2px")
    out.append("    classDef visited fill:#cfe8cf,color:#000")
    for v in sorted(visited - {cur}):
        if v in PHASES:
            out.append(f"    class {v} visited")
    if cur in PHASES:
        out.append(f"    class {cur} current")
    return "\n".join(out)


def render(st: State, visited: set) -> str:
    keys = ["id", "title", "owner", "phase", "previous", "builder", "playbook", "branch", "created", "updated"]
    meta_lines = [f"{k}: {st.meta[k]}" for k in keys if st.meta.get(k)]
    meta_lines += [f"{k}: {v}" for k, v in st.meta.items() if k not in keys and v]
    parts = ["---", *meta_lines, "---", f"# {st.meta.get('title', st.id)}", ""]
    for name in SECTIONS:
        parts.append(f"## {name}")
        if name == "Tasks":
            parts.extend(t.render() for t in st.tasks)
        else:
            body = st.sections.get(name, "").strip("\n")
            if body:
                parts.append(body)
        parts.append("")
    for name, body in st.sections.items():
        if name not in SECTIONS:
            parts += [f"## {name}", body.strip("\n"), ""]
    parts += ["## State", CHART_START, "```mermaid", chart(st, visited), "```", CHART_END, ""]
    return "\n".join(parts)


# ---------------------------------------------------------------- log

def clean_cell(v: str) -> str:
    v = re.sub(r"[\t\r\n]+", " ", str(v)).strip()
    if v and v[0] in "=+-@":
        v = "'" + v
    return v


def read_log(d: Path) -> list:
    p = d / "DECISIONS.tsv"
    if not p.exists():
        return []
    rows = []
    for line in p.read_text(encoding="utf-8").replace("\r\n", "\n").split("\n")[1:]:
        if line.strip():
            cells = line.split("\t")
            rows.append(dict(zip(LOG_HEADER, cells + [""] * (len(LOG_HEADER) - len(cells)))))
    return rows


def append_log(d: Path, phase: str, decision: str, why: str, evidence: str = "", result: str = "") -> None:
    p = d / "DECISIONS.tsv"
    new = not p.exists()
    with p.open("a", encoding="utf-8", newline="\n") as f:
        if new:
            f.write("\t".join(LOG_HEADER) + "\n")
        f.write("\t".join(clean_cell(c) for c in (now(), phase, decision, why, evidence, result)) + "\n")


def visited_phases(d: Path) -> set:
    seen = {"plan"}
    for r in read_log(d):
        if r["phase"] in PHASES:
            seen.add(r["phase"])
    return seen


# ---------------------------------------------------------------- io

def load(d: Path) -> State:
    p = d / "STATE.md"
    if not p.exists():
        raise StateError(f"no task at {d} (run: state.py init)")
    return parse(p.read_text(encoding="utf-8"))


def save(d: Path, st: State) -> None:
    st.meta["updated"] = now()
    text = render(st, visited_phases(d))
    fd, tmp = tempfile.mkstemp(dir=d, prefix=".STATE.", suffix=".tmp")
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, d / "STATE.md")


# ---------------------------------------------------------------- playbooks

HERE = Path(__file__).resolve().parent
STEP_RE = re.compile(r"^(\d+)\. (.+)$")


def playbook_file(name: str) -> Path:
    """iskandar-mode's own playbooks first, then pstack's (poteto-mode/playbooks)."""
    ours = HERE.parent.parent / "iskandar-mode" / "playbooks" / f"{name}.md"
    if ours.exists():
        return ours
    sys.path.insert(0, str(HERE.parent.parent / "iskandar-mode" / "scripts"))
    try:
        import pstack_root  # noqa: E402
        root = pstack_root.find(Path(os.environ.get("ISKANDAR_HOME") or Path.home()))
    except ImportError:
        root = None
    finally:
        sys.path.pop(0)
    if root is None:
        raise StateError(f"playbook {name!r}: not an iskandar-mode playbook and pstack is not installed")
    theirs = root / "skills" / "poteto-mode" / "playbooks" / f"{name}.md"
    if not theirs.exists():
        names = sorted(p.stem for p in theirs.parent.glob("*.md"))
        raise StateError(f"no playbook {name!r}; pstack has: {', '.join(names)}")
    return theirs


def playbook_steps(path: Path) -> list:
    """Each numbered step's first sentence, verbatim, as 'step N: ...'."""
    steps = []
    for line in path.read_text(encoding="utf-8").replace("\r\n", "\n").split("\n"):
        m = STEP_RE.match(line)
        if m:
            first = re.split(r"(?<=[.!?])\s", m.group(2).strip(), maxsplit=1)[0]
            steps.append(f"step {m.group(1)}: {first[:200]}")
    return steps


# ---------------------------------------------------------------- checks

def problems(st: State, d: Path) -> list:
    out = []
    if not ID_RE.match(st.id or ""):
        out.append("frontmatter: missing or bad id")
    elif d.name != st.id:
        out.append(f"frontmatter: id {st.id!r} does not match folder {d.name!r}")
    if st.phase not in PHASES:
        out.append(f"frontmatter: phase {st.phase!r} is not one of {', '.join(PHASES)}")
    if st.meta.get("owner") not in OWNERS:
        out.append(f"frontmatter: owner {st.meta.get('owner')!r} is not one of {', '.join(OWNERS)}")
    if st.phase in ("paused", "blocked") and st.meta.get("previous") not in ACTIVE:
        out.append(f"frontmatter: {st.phase} task needs previous: one of {', '.join(ACTIVE)}")
    if st.phase in ("paused", "blocked") and not st.sections.get("Handoff", "").strip():
        out.append(f"Handoff: a {st.phase} task needs a handoff note")
    if not st.sections.get("Goal", "").strip():
        out.append("Goal: empty")
    for n, t in enumerate(st.tasks, 1):
        if t.status == "skip" and not t.reason:
            out.append(f"Tasks: task {n} is skipped with no reason (write '-- skip: <reason>')")
    if st.phase in ("review", "done"):
        open_ = [n for n, t in enumerate(st.tasks, 1) if t.status == "open"]
        if open_:
            out.append(f"Tasks: {st.phase} with open tasks {open_}")
        if not st.sections.get("Walkthrough", "").strip():
            out.append(f"Walkthrough: {st.phase} needs evidence (commands run and their output)")
    if (d / "DECISIONS.tsv").exists():
        head = (d / "DECISIONS.tsv").read_text(encoding="utf-8").split("\n", 1)[0].rstrip("\r")
        if head.split("\t") != list(LOG_HEADER):
            out.append("DECISIONS.tsv: header is not " + " ".join(LOG_HEADER))
        for n, r in enumerate(read_log(d), 2):
            if not r["ts"] or not r["decision"]:
                out.append(f"DECISIONS.tsv: line {n} has no ts or decision")
    return out


def gate(st: State, to: str, by: str) -> None:
    """Rules a transition must meet. Raise StateError with what is missing."""
    frm = st.phase
    if to in ("paused", "blocked"):
        if frm not in ACTIVE:
            raise StateError(f"can only {to[:-2] if to.endswith('ed') else to} an active task (phase is {frm})")
        return
    if frm in ("paused", "blocked"):
        if to != st.meta.get("previous"):
            raise StateError(f"a {frm} task resumes to {st.meta.get('previous')!r}, not {to!r}")
        return
    if to not in TRANSITIONS.get(frm, ()):
        allowed = ", ".join(TRANSITIONS.get(frm, ())) or "nothing"
        raise StateError(f"{frm} -> {to} is not allowed (from {frm}: {allowed})")
    if frm == "plan":
        if not st.sections.get("Plan", "").strip():
            raise StateError("leaving plan needs a Plan section")
        if not st.tasks:
            raise StateError("leaving plan needs at least one task")
    if to in ("review", "done"):
        open_ = [n for n, t in enumerate(st.tasks, 1) if t.status == "open"]
        if open_:
            raise StateError(f"{to} needs every task done or skipped with a reason; open: {open_}")
        if not st.sections.get("Walkthrough", "").strip():
            raise StateError(f"{to} needs a Walkthrough with the evidence")
    if to == "done":
        builder = st.meta.get("builder", "")
        if by not in OWNERS:
            raise StateError("done needs --by claude|antigravity|human (who reviewed)")
        if builder and by == builder:
            raise StateError(f"done must be reviewed by someone other than the builder ({builder})")


# ---------------------------------------------------------------- commands

def cmd_init(args) -> int:
    d = task_dir(args, args.id)
    if (d / "STATE.md").exists():
        st = load(d)
        print(f"exists: {d / 'STATE.md'} (phase {st.phase}, owner {st.meta.get('owner')})")
        return 0
    if args.owner not in OWNERS:
        raise StateError(f"owner must be one of {', '.join(OWNERS)}")
    pb = args.playbook.strip()
    if pb.startswith("none"):
        reason = pb.partition(":")[2].strip()
        if not reason:
            raise StateError("--playbook none needs a reason: --playbook 'none: <why no playbook fits>'")
        name, tasks, source = "none", [], reason
    else:
        path = playbook_file(pb)
        name, tasks, source = pb, [Task(t) for t in playbook_steps(path)], str(path)
    d.mkdir(parents=True, exist_ok=True)
    st = State(meta={"id": args.id, "title": args.title, "owner": args.owner, "phase": "plan",
                     "playbook": name, "branch": args.branch or "", "created": now()},
               sections={"Goal": args.goal.strip()}, tasks=tasks)
    append_log(d, "plan", f"opened task {args.id}", args.goal, args.evidence or "", "open")
    append_log(d, "plan", f"playbook {name}" + (f": {len(tasks)} steps copied" if tasks else ""),
               "matched to the task" if name != "none" else source, source if name != "none" else "", "")
    save(d, st)
    print(d / "STATE.md")
    return 0


def read_text_arg(args) -> str:
    if getattr(args, "file", None):
        return Path(args.file).read_text(encoding="utf-8").strip()
    if args.text == "-":
        return sys.stdin.read().strip()
    return args.text.strip()


def cmd_section(name):
    def run(args) -> int:
        d = task_dir(args, args.id)
        st = load(d)
        st.sections[name] = read_text_arg(args)
        save(d, st)
        return 0
    return run


def cmd_task(args) -> int:
    d = task_dir(args, args.id)
    st = load(d)
    if args.action == "add":
        for text in args.items:
            st.tasks.append(Task(text.strip()))
    else:
        n = int(args.items[0])
        if not 1 <= n <= len(st.tasks):
            raise StateError(f"no task {n} (there are {len(st.tasks)})")
        t = st.tasks[n - 1]
        if args.action == "done":
            t.status, t.reason = "done", ""
        elif args.action == "undo":
            t.status, t.reason = "open", ""
        elif args.action == "skip":
            if not args.reason:
                raise StateError("skip needs --reason")
            t.status, t.reason = "skip", args.reason.strip()
            append_log(d, st.phase, f"skipped task {n}: {t.text}", args.reason, "", "skipped")
    save(d, st)
    return 0


def cmd_phase(args) -> int:
    d = task_dir(args, args.id)
    st = load(d)
    to = args.to
    if to not in PHASES:
        raise StateError(f"unknown phase {to!r}")
    frm = st.phase
    if frm == to:
        print(f"already {to}")
        return 0
    gate(st, to, args.by or "")
    if to in ("paused", "blocked"):
        st.meta["previous"] = frm
        st.meta["pause_reason"] = args.reason
        if args.next:
            st.sections["Handoff"] = f"Next: {args.next.strip()}"
        if not st.sections.get("Handoff", "").strip():
            raise StateError(f"{to} needs a handoff note: pass --next '<first action on resume>'")
    else:
        st.meta.pop("previous", None)
        st.meta.pop("pause_reason", None)
    if to == "build" and frm in ("plan", "verify", "review", "done"):
        st.meta["builder"] = st.meta.get("owner", "")
    st.meta["phase"] = to
    append_log(d, to, f"phase {frm} -> {to}", args.reason, args.evidence or "", args.result or to)
    save(d, st)
    return 0


def cmd_log(args) -> int:
    d = task_dir(args, args.id)
    st = load(d)
    append_log(d, args.phase or st.phase, args.decision, args.why, args.evidence or "", args.result or "")
    save(d, st)
    return 0


def cmd_handoff(args) -> int:
    d = task_dir(args, args.id)
    st = load(d)
    if args.to not in OWNERS:
        raise StateError(f"--to must be one of {', '.join(OWNERS)}")
    need = HANDOFF_PHASES[args.purpose]
    if st.phase not in need:
        hint = {"review": "finish the tasks, write the Walkthrough, then `phase <id> review`"}.get(args.purpose, "")
        raise StateError(f"a handoff for {args.purpose} needs phase {' or '.join(need)} (phase is {st.phase})"
                         + (f": {hint}" if hint else ""))
    frm = st.meta.get("owner")
    note = [f"From: {frm}", f"To: {args.to}", f"For: {args.purpose}", f"Next: {args.next.strip()}"]
    if args.questions:
        note.append(f"Open questions: {args.questions.strip()}")
    if args.files:
        note.append(f"Key files: {args.files.strip()}")
    st.sections["Handoff"] = "\n".join(note)
    st.meta["owner"] = args.to
    append_log(d, st.phase, f"handoff {frm} -> {args.to} for {args.purpose}", args.next, args.evidence or "", "handed off")
    save(d, st)
    return 0


def summary(st: State, d: Path, brief: bool) -> str:
    total = len(st.tasks)
    closed = sum(t.status != "open" for t in st.tasks)
    line = f"{st.id}  [{st.phase}]  owner={st.meta.get('owner')}  tasks {closed}/{total}  {st.meta.get('title', '')}"
    if brief:
        return line
    out = [line, f"  dir: {d}"]
    if st.meta.get("branch"):
        out.append(f"  branch: {st.meta['branch']}")
    nxt = next((t for t in st.tasks if t.status == "open"), None)
    if nxt:
        out.append(f"  next task: {nxt.text}")
    h = st.sections.get("Handoff", "").strip()
    if h:
        out.append("  handoff: " + h.replace("\n", " | "))
    rows = read_log(d)[-3:]
    for r in rows:
        out.append(f"  log {r['ts']} {r['phase']}: {r['decision']} ({r['result']})")
    return "\n".join(out)


def all_tasks(args) -> list:
    root = state_dir(args)
    if not root.exists():
        return []
    return sorted(p for p in root.iterdir() if (p / "STATE.md").exists())


def cmd_status(args) -> int:
    if args.id:
        d = task_dir(args, args.id)
        print(summary(load(d), d, args.brief))
        return 0
    found = False
    for d in all_tasks(args):
        st = load(d)
        if st.phase == "done" and not args.all:
            continue
        if args.owner and st.meta.get("owner") != args.owner:
            continue
        found = True
        print(summary(st, d, args.brief))
    if not found and not args.quiet:
        print("no open tasks")
    return 0


def cmd_resume(args) -> int:
    d = task_dir(args, args.id)
    st = load(d)
    rows = read_log(d)
    last_own = -1
    for n, r in enumerate(rows):
        if r["phase"] == "start" and args.run in r["evidence"]:
            last_own = n
    others = [r for r in rows[last_own + 1:] if not (r["phase"] == "start" and args.run in r["evidence"])]
    rng = f"{others[0]['ts']}..{others[-1]['ts']}" if others else "none"
    if args.owner:
        st.meta["owner"] = args.owner
    append_log(d, "start", f"resumed by {args.run}", f"rows from other runs: {rng}", f"run {args.run}", st.phase)
    save(d, st)
    print(summary(st, d, False))
    return 0


def cmd_check(args) -> int:
    dirs = [task_dir(args, args.id)] if args.id else all_tasks(args)
    bad = 0
    for d in dirs:
        try:
            ps = problems(load(d), d)
        except StateError as e:
            ps = [str(e)]
        for p in ps:
            print(f"{d.name}: {p}")
        bad += bool(ps)
    if not args.quiet:
        print(f"checked {len(dirs)} task(s), {bad} with problems")
    return 1 if bad else 0


def cmd_agent(args) -> int:
    """Brief a helper agent (Antigravity teamwork style): agents/<role>/BRIEFING.md, progress.md."""
    d = task_dir(args, args.id)
    st = load(d)
    if not ID_RE.match(args.role):
        raise StateError(f"bad role {args.role!r}")
    a = d / "agents" / args.role
    a.mkdir(parents=True, exist_ok=True)
    brief = read_text_arg(args)
    (a / "BRIEFING.md").write_text(
        f"# Briefing: {args.role}\n\nTask: {st.meta.get('title', st.id)} ({st.id})\n"
        f"State: {d / 'STATE.md'}\n\n## Goal\n{st.sections.get('Goal', '').strip()}\n\n## Your part\n{brief}\n\n"
        f"## When done\nWrite {a / 'handoff.md'}: what changed, commands run with their output, what is left.\n",
        encoding="utf-8", newline="\n")
    prog = a / "progress.md"
    if not prog.exists():
        prog.write_text(f"# Progress: {args.role}\n\n- [ ] read BRIEFING.md\n", encoding="utf-8", newline="\n")
    append_log(d, st.phase, f"briefed helper {args.role}", brief.split("\n")[0][:200], str(a / "BRIEFING.md"), "briefed")
    save(d, st)
    print(a / "BRIEFING.md")
    return 0


def cmd_chart(args) -> int:
    d = task_dir(args, args.id)
    st = load(d)
    save(d, st)
    print(chart(st, visited_phases(d)))
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="state.py", description=__doc__.split("\n")[0])
    p.add_argument("--root", help="repository root (default: nearest folder with .git)")
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("init", help="open a task")
    s.add_argument("id"); s.add_argument("--title", required=True); s.add_argument("--goal", required=True)
    s.add_argument("--owner", default="claude"); s.add_argument("--branch"); s.add_argument("--evidence")
    s.add_argument("--playbook", required=True,
                   help="the matched playbook (bug-fix, feature, investigation, handoff, ...): its steps become the tasks; "
                        "or 'none: <reason>'")
    s.set_defaults(fn=cmd_init)

    for name in ("plan", "walkthrough", "goal"):
        s = sub.add_parser(name, help=f"replace the {name.title()} section")
        s.add_argument("id"); g = s.add_mutually_exclusive_group(required=True)
        g.add_argument("--text"); g.add_argument("--file")
        s.set_defaults(fn=cmd_section(name.title()))

    s = sub.add_parser("task", help="add | done N | skip N --reason | undo N")
    s.add_argument("id"); s.add_argument("action", choices=("add", "done", "skip", "undo"))
    s.add_argument("items", nargs="+"); s.add_argument("--reason")
    s.set_defaults(fn=cmd_task)

    s = sub.add_parser("phase", help="move the task through its lifecycle")
    s.add_argument("id"); s.add_argument("to"); s.add_argument("--reason", required=True)
    s.add_argument("--evidence"); s.add_argument("--result"); s.add_argument("--by"); s.add_argument("--next")
    s.set_defaults(fn=cmd_phase)

    s = sub.add_parser("log", help="append a decision row")
    s.add_argument("id"); s.add_argument("--decision", required=True); s.add_argument("--why", required=True)
    s.add_argument("--evidence"); s.add_argument("--result"); s.add_argument("--phase")
    s.set_defaults(fn=cmd_log)

    s = sub.add_parser("handoff", help="pass the task to another agent or the human")
    s.add_argument("id"); s.add_argument("--to", required=True); s.add_argument("--next", required=True)
    s.add_argument("--for", dest="purpose", required=True, choices=tuple(HANDOFF_PHASES),
                   help="what the receiver does: plan, build, review, or decide (the owner's call)")
    s.add_argument("--questions"); s.add_argument("--files"); s.add_argument("--evidence")
    s.set_defaults(fn=cmd_handoff)

    s = sub.add_parser("resume", help="pick a task up: print it and log a start row")
    s.add_argument("id"); s.add_argument("--run", required=True); s.add_argument("--owner")
    s.set_defaults(fn=cmd_resume)

    s = sub.add_parser("status", help="one task, or every open task")
    s.add_argument("id", nargs="?"); s.add_argument("--brief", action="store_true")
    s.add_argument("--all", action="store_true"); s.add_argument("--owner"); s.add_argument("--quiet", action="store_true")
    s.set_defaults(fn=cmd_status)

    s = sub.add_parser("check", help="lint one task or all; exit 1 on problems")
    s.add_argument("id", nargs="?"); s.add_argument("--quiet", action="store_true")
    s.set_defaults(fn=cmd_check)

    s = sub.add_parser("agent", help="brief a helper agent under agents/<role>/")
    s.add_argument("id"); s.add_argument("role"); g = s.add_mutually_exclusive_group(required=True)
    g.add_argument("--text"); g.add_argument("--file")
    s.set_defaults(fn=cmd_agent)

    s = sub.add_parser("chart", help="redraw and print the Mermaid chart")
    s.add_argument("id"); s.set_defaults(fn=cmd_chart)
    return p


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.fn(args)
    except StateError as e:
        print(f"state.py: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
