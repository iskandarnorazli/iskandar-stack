"""The no-attribution guard refuses commits and GitHub writes that credit an AI, and nothing else."""
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "src" / "skills" / "iskandar-mode" / "scripts" / "no_attribution.py"
sys.path.insert(0, str(SCRIPT.parent))
import no_attribution as na  # noqa: E402


def run_hook(command: str, cwd: str = ".", tool: str = "Bash"):
    data = json.dumps({"tool_name": tool, "tool_input": {"command": command}, "cwd": cwd})
    return subprocess.run([sys.executable, str(SCRIPT)], input=data, capture_output=True, text=True)


class Guard(unittest.TestCase):
    def test_refuses_attribution_in_a_commit_message(self):
        for line in ("Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
                     "Claude-Session: https://claude.ai/code/session_01AB",
                     "\U0001F916 Generated with [Claude Code](https://claude.com/claude-code)"):
            r = run_hook(f'git -c user.name=X commit -q -m "fix\n\n{line}"')
            self.assertEqual(r.returncode, 2, line)
            self.assertIn("no AI attribution", r.stderr)

    def test_refuses_attribution_in_a_body_file(self):
        with tempfile.TemporaryDirectory() as d:
            (Path(d) / "body.md").write_text("Gate evidence\n\n_Generated by [Claude Code](https://claude.ai/code)_\n", encoding="utf-8")
            (Path(d) / "msg.txt").write_text("fix\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n", encoding="utf-8")
            self.assertEqual(run_hook("gh api repos/o/r/issues/1/comments -F body=@body.md", d).returncode, 2)
            self.assertEqual(run_hook("gh pr create --body-file body.md --title t", d).returncode, 2)
            self.assertEqual(run_hook("git commit -F msg.txt", d).returncode, 2)

    def test_lets_clean_writes_and_every_read_through(self):
        with tempfile.TemporaryDirectory() as d:
            (Path(d) / "body.md").write_text("Gate evidence: 23 of 23 checks pass.\n", encoding="utf-8")
            for cmd in ('git commit -q -m "fix: one buffer"',
                        "gh api repos/o/r/issues/1/comments -F body=@body.md",
                        # Reads and searches of the same strings are not writes.
                        "grep -rn 'Co-Authored-By: Claude' .",
                        "git log --grep='co-authored-by: claude' --format=%h",
                        "gh api repos/o/r/issues/comments -q '.[]|select(.body|test(\"Generated by [Claude\"))'"):
                self.assertEqual(run_hook(cmd, d).returncode, 0, cmd)

    def test_other_tools_and_bad_input_pass(self):
        self.assertEqual(run_hook("Co-Authored-By: Claude", tool="Write").returncode, 0)
        r = subprocess.run([sys.executable, str(SCRIPT)], input="not json", capture_output=True, text=True)
        self.assertEqual(r.returncode, 0)

    def test_a_missing_body_file_is_not_an_error(self):
        self.assertEqual(na.check("gh api x -F body=@nowhere.md", Path(".")), "")


if __name__ == "__main__":
    unittest.main()
